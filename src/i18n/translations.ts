export const translations: Record<Locale, TranslationDict> = { ru, en };

export function getServerT(locale: Locale) {
  const dict = translations[locale] ?? translations.ru;
  return (key: string, params?: Record<string, string | number>) => {
    const parts = key.split('.');
    let val: unknown = dict;
    for (const p of parts) val = (val as Record<string, unknown>)?.[p];
    if (typeof val !== 'string') return key;
    return val.replace(/\{(\w+)\}/g, (_, n: string) =>
      params?.[n] !== undefined ? String(params[n]) : `{${n}}`
    );
  };
}
